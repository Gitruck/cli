/** 词表最长词长（护栏扫描上界）；随 `CJK_GUARD_WORDS` 自动跟随，MUST NOT 写死。 */
const GUARD_WORD_MAX_LEN = Math.max(...[...CJK_GUARD_WORDS].map((w) => [...w].length));

/** chars[..cut) 的结尾是否正好是词表里某个词的词尾（量词/副词悬挂判据的豁免口）。 */
export function endsGuardWord(chars: string[], cut: number): boolean {
	for (let len = 2; len <= GUARD_WORD_MAX_LEN; len++) {
		const s = cut - len;
		if (s < 0) break;
		if (CJK_GUARD_WORDS.has(chars.slice(s, cut).join(""))) return true;
	}
	return false;
}

/** 第 ② 级词表护栏：切点落在附着字前 / 悬挂字后 / 词表命中词的内部即为非法。 */
export function splitsWord(chars: string[], cut: number): boolean {
	if (CJK_NO_LEAD_CHARS.has(chars[cut] ?? "")) return true;
	if (CJK_NO_TRAIL_CHARS.has(chars[cut - 1] ?? "") && !endsGuardWord(chars, cut)) return true;
	// O(1) 查表 + 最长词长上界扫描（零 npm 依赖）：任一命中词**严格跨过**切点即非法。
	for (let len = 2; len <= GUARD_WORD_MAX_LEN; len++) {
		for (let k = 1; k < len; k++) {
			const s = cut - k;
			if (s < 0 || s + len > chars.length) continue;
			if (CJK_GUARD_WORDS.has(chars.slice(s, s + len).join(""))) return true;
		}
	}
	return false;
}
